"""Likelihood-correct shield-aware policies under a fixed operational oracle.

ExactJointShield conditions the factorized policy on raw admissibility. The
scalable SequentialSafeShield instead uses a documented restricted support:
each chosen prefix must remain feasible when later agents choose native NOOP.
It is not an exact sampler from the fully conditioned joint distribution.
"""
from __future__ import annotations
import math
import numpy as np
import torch


def _check(logits, oracle):
    if logits.ndim != 3 or logits.shape[-1] != 5 or logits.shape[0] != oracle.batch_size or logits.shape[1] != oracle.n_agents:
        raise ValueError('logits[B,N,5] and matching fixed-state oracle required')
    if not torch.isfinite(logits).all():
        raise ValueError('finite logits required')


def _mask(oracle, candidates, device):
    valid = oracle.admissible(candidates, require_physical=True)
    return torch.as_tensor(valid, device=device, dtype=torch.bool)


def _action_tensor(actions, shape, device):
    raw=torch.as_tensor(actions,device=device)
    if raw.dtype not in (torch.uint8,torch.int8,torch.int16,torch.int32,torch.int64):
        raise ValueError('integer action tensor required')
    if raw.shape!=shape or not ((raw>=0)&(raw<5)).all():
        raise ValueError('actions[B,N] in0..4')
    return raw.to(dtype=torch.long)


class ExactJointShield:
    """q(A|s) proportional to product pi_i(A_i|s) on raw-admissible A."""
    entropy_estimator = 'exact_joint_entropy'

    def __init__(self, logits, oracle, *, max_joint_actions=65536):
        _check(logits, oracle)
        self.logits, self.oracle = logits, oracle
        b, n, a = logits.shape
        if a ** n > max_joint_actions:
            raise ValueError('exact joint shield exceeds explicit enumeration cap')
        grid = np.indices((a,) * n, dtype=np.int64).reshape(n, -1).T.copy()
        self.actions = torch.as_tensor(grid, device=logits.device)
        candidates = self.actions.unsqueeze(0).expand(b, -1, -1)
        self.valid = _mask(oracle, candidates, logits.device)
        if not self.valid.any(dim=1).all():
            raise ValueError('empty admissible joint support')
        logpi = logits.log_softmax(-1)
        score = sum(logpi[:, i, :][:, self.actions[:, i]] for i in range(n))
        self.log_weights = score.masked_fill(~self.valid, -torch.inf)
        self.log_normalizer = torch.logsumexp(self.log_weights, dim=1)
        self.log_probs = self.log_weights - self.log_normalizer[:, None]
        self.probs = self.log_probs.exp()
        self._strides = torch.tensor([a ** (n - 1 - i) for i in range(n)], device=logits.device)

    def sample(self, generator=None):
        k = torch.multinomial(self.probs, 1, generator=generator).squeeze(1)
        return self.actions[k]

    def log_prob(self, actions):
        a = _action_tensor(actions,self.logits.shape[:2],self.logits.device)
        index = (a * self._strides).sum(dim=-1)
        return self.log_probs.gather(1, index[:, None]).squeeze(1)

    def entropy(self, **_):
        finite = self.log_probs.masked_fill(~self.valid, 0.)
        return -(self.probs * finite).sum(dim=1)


class SequentialSafeShield:
    """Autoregressive feasible-prefix policy with a native-NOOP completion.

    Every nonempty prefix mask is generated by the operational predicate, not
    by trainable logits. Joint log likelihood is the sum of normalized prefix
    log probabilities. The support depends on the announced order; by default
    order rotates by public environment step to avoid a permanent first agent.
    Joint entropy uses a fresh-policy score-gradient Monte Carlo estimator.
    """
    entropy_estimator = 'unbiased_score_gradient_MC_joint_entropy'

    def __init__(self, logits, oracle, *, order=None):
        _check(logits, oracle)
        self.logits, self.oracle = logits, oracle
        b, n, _ = logits.shape
        if order is None:
            order = [[(int(s['t']) + j) % n for j in range(n)] for s in oracle.snapshots]
        order = order.detach().cpu().numpy() if hasattr(order,'detach') else np.asarray(order)
        if order.shape == (n,):
            order = np.broadcast_to(order, (b, n)).copy()
        if order.shape != (b, n) or order.dtype.kind not in 'iu' or any(sorted(row.tolist()) != list(range(n)) for row in order):
            raise ValueError('order must contain each agent exactly once per state')
        self.order = torch.as_tensor(order, device=logits.device)

    def _traverse(self, actions=None, generator=None):
        b, n, _ = self.logits.shape
        device = self.logits.device
        prefix = torch.zeros((b, n), dtype=torch.long, device=device)
        chosen = None if actions is None else _action_tensor(actions,(b,n),device)
        total = torch.zeros(b, device=device, dtype=self.logits.dtype)
        valid_path = torch.ones(b, device=device, dtype=torch.bool)
        rows = torch.arange(b, device=device)
        for j in range(n):
            agent = self.order[:, j]
            proposals = prefix[:, None, :].expand(-1, 5, -1).clone()
            proposals[rows[:, None], torch.arange(5, device=device)[None, :], agent[:, None]] = torch.arange(5, device=device)[None, :]
            mask = _mask(self.oracle, proposals, device)
            if not mask.any(dim=1).all():
                raise ValueError('safe-completion prefix unexpectedly has empty support')
            local = self.logits[rows, agent].masked_fill(~mask, -torch.inf)
            logp = local.log_softmax(dim=-1)
            if chosen is None:
                action = torch.multinomial(logp.exp(), 1, generator=generator).squeeze(1)
            else:
                action = chosen[rows, agent]
                valid_path &= mask[rows, action]
            selected = logp[rows, action]
            total = total + selected.masked_fill(~valid_path, 0.)
            # Continue a valid NOOP path when evaluating an out-of-support
            # action; final result is -inf, with no infeasible oracle calls.
            prefix[rows, agent] = torch.where(valid_path, action, torch.zeros_like(action))
        return prefix, total.masked_fill(~valid_path, -torch.inf)

    def sample(self, generator=None):
        return self._traverse(generator=generator)[0]

    def log_prob(self, actions):
        return self._traverse(actions=actions)[1]

    def entropy(self, samples=1, generator=None):
        if not isinstance(samples, int) or samples < 1:
            raise ValueError('positive entropy sample count')
        estimates = []
        for _ in range(samples):
            _, logq = self._traverse(generator=generator)
            value = -logq.detach()
            surrogate = -logq.detach() * logq
            estimates.append(value + surrogate - surrogate.detach())
        return torch.stack(estimates).mean(dim=0)


class PreparedSequentialLikelihood:
    """Reuse only fixed-state, fixed-observed-prefix masks across PPO epochs.

    A sampled shield trajectory has a deterministic mask at each prefix. Those
    masks depend on the immutable state/order and stored actions, not on updated
    policy parameters. Constructing this object validates all stored prefixes
    once; .log_prob differentiates the current logits with no new checker calls.
    It cannot sample trajectories or estimate entropy, since a fresh trajectory
    may encounter different prefixes. Out-of-support stored data is rejected.
    """
    def __init__(self, oracle, actions, *, order=None):
        raw=actions.detach().cpu().numpy() if hasattr(actions,'detach') else np.asarray(actions)
        b,n=oracle.batch_size,oracle.n_agents
        if raw.shape!=(b,n) or raw.dtype.kind not in 'iu' or np.any((raw<0)|(raw>4)):
            raise ValueError('integer stored actions[B,N] in0..4 required')
        self.actions=raw.astype(np.int64,copy=True)
        self.batch_size,self.n_agents,self.n_actions=b,n,5
        if order is None:
            order=[[(int(s['t'])+j)%n for j in range(n)] for s in oracle.snapshots]
        order=np.asarray(order)
        if order.shape==(n,):order=np.broadcast_to(order,(b,n))
        if order.shape!=(b,n) or order.dtype.kind not in 'iu' or any(sorted(x.tolist())!=list(range(n)) for x in order):
            raise ValueError('stored prefix order must be an agent permutation per state')
        self.order=order.astype(np.int64,copy=True)
        self.masks=np.empty((b,n,5),dtype=bool)
        prefix=np.zeros((b,n),dtype=np.int64);rows=np.arange(b)
        before=dict(oracle.counters)
        for j in range(n):
            agent=self.order[:,j]
            proposals=np.broadcast_to(prefix[:,None,:],(b,5,n)).copy()
            proposals[rows[:,None],np.arange(5)[None,:],agent[:,None]]=np.arange(5)[None,:]
            mask=np.asarray(oracle.admissible(proposals,require_physical=True),dtype=bool)
            if mask.shape!=(b,5) or not mask.any(axis=1).all():
                raise ValueError('invalid prepared shield prefix mask')
            chosen=self.actions[rows,agent]
            if not mask[rows,chosen].all():
                raise ValueError('stored actions outside sequential safe-completion support')
            self.masks[:,j,:]=mask
            prefix[rows,agent]=chosen
        self.preparation_work={k:v-before.get(k,0) for k,v in oracle.counters.items()}
        for x in (self.actions,self.order,self.masks):x.setflags(write=False)

    def log_prob(self, logits):
        if logits.shape!=(self.batch_size,self.n_agents,5) or not torch.isfinite(logits).all():
            raise ValueError('matching finite logits[B,N,5] required')
        order=torch.tensor(self.order,device=logits.device,dtype=torch.long)
        mask=torch.tensor(self.masks,device=logits.device,dtype=torch.bool)
        ordered=logits.gather(1,order[:,:,None].expand(-1,-1,5))
        logp=ordered.masked_fill(~mask,-torch.inf).log_softmax(-1)
        actions=np.take_along_axis(self.actions,self.order,axis=1)
        selected=torch.tensor(actions,device=logits.device,dtype=torch.long)
        return logp.gather(2,selected[:,:,None]).squeeze(-1).sum(-1)

    def subset(self, indices):
        indices=np.asarray(list(indices),dtype=np.int64)
        if indices.ndim!=1 or not len(indices) or np.any(indices<0) or np.any(indices>=self.batch_size):
            raise ValueError('nonempty valid prepared-likelihood subset')
        child=object.__new__(type(self))
        child.actions=self.actions[indices];child.order=self.order[indices];child.masks=self.masks[indices]
        child.batch_size,child.n_agents,child.n_actions=len(indices),self.n_agents,5
        child.preparation_work=self.preparation_work
        for x in (child.actions,child.order,child.masks):x.setflags(write=False)
        return child
